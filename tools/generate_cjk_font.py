#!/usr/bin/env python3
"""Generate the 16x16 CJK glyph table used by ZectrixCanvas.

Scans the UI sources for non-ASCII characters and renders exactly those from
GNU Unifont (SIL OFL 1.1), a native 16x16 pixel font, into
components/zectrix_demo_ui/font/zectrix_cjk_font_16.h.

    python3 tools/generate_cjk_font.py [--font unifont.otf]

Without --font, Unifont is downloaded once into ~/.cache/zectrix/.

Re-run after adding Chinese text to an app.
"""
import argparse
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SCAN = [ROOT / "main/apps", ROOT / "components/zos"]
OUT = ROOT / "components/zectrix_demo_ui/font/zectrix_cjk_font_16.h"
UNIFONT_URL = "https://unifoundry.com/pub/unifont/unifont-18.0.01/font-builds/unifont-18.0.01.otf"
CACHE = Path.home() / ".cache/zectrix/unifont-18.0.01.otf"


def default_font():
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        print("downloading", UNIFONT_URL)
        urllib.request.urlretrieve(UNIFONT_URL, CACHE)
    return str(CACHE)


def used_chars():
    chars = set()
    for base in SCAN:
        for path in base.rglob("*"):
            if path.suffix in {".cc", ".h"}:
                chars.update(c for c in path.read_text(encoding="utf-8") if ord(c) > 0x7F)
    return sorted(chars)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font")
    args = ap.parse_args()
    font = ImageFont.truetype(args.font or default_font(), 16)
    chars = used_chars()
    lines = [
        "// Generated by tools/generate_cjk_font.py from GNU Unifont (SIL OFL 1.1).",
        "// 16x16, one uint16_t per row, MSB = left pixel. Sorted by code point.",
        "#ifndef ZECTRIX_CJK_FONT_16_H_",
        "#define ZECTRIX_CJK_FONT_16_H_",
        "",
        "#include <cstdint>",
        "",
        "struct ZectrixCjkGlyph {",
        "    uint32_t code_point;",
        "    uint16_t rows[16];",
        "};",
        "",
        "inline constexpr ZectrixCjkGlyph kZectrixCjkFont16[] = {",
    ]
    for ch in chars:
        img = Image.new("L", (16, 16), 255)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"
        draw.text((0, 0), ch, font=font, fill=0, anchor="la")
        rows = []
        for y in range(16):
            rows.append(sum(1 << (15 - x) for x in range(16) if img.getpixel((x, y)) < 128))
        lines.append("    {0x%04X, {%s}},  // %s" % (ord(ch), ", ".join("0x%04x" % r for r in rows), ch))
    lines += ["};", "", "#endif  // ZECTRIX_CJK_FONT_16_H_", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(chars)} glyphs -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
