#!/usr/bin/env python3
"""Generate the 1bpp weather icons (48x48 and 32x32) used by the clock/weather app.

Glyphs come from Font Awesome Free (solid, SIL OFL 1.1 for the font), fitted and
centred in the box, thresholded to black/white. Output:
main/apps/weather/weather_icons.h

    python3 tools/generate_weather_icons.py [--font fa-solid-900.ttf]

Without --font the font is downloaded once into ~/.cache/zectrix/.
"""
import argparse
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "main/apps/weather/weather_icons.h"
URL = "https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@6.5.2/webfonts/fa-solid-900.ttf"
CACHE = Path.home() / ".cache/zectrix/fa-solid-900.ttf"
SIZES = (48, 32)
# Order must match enum class WeatherIcon in weather.h.
ICONS = [
    ("kSunny", 0xF185),         # sun
    ("kClearNight", 0xF186),    # moon
    ("kPartlyCloudy", 0xF6C4),  # cloud-sun
    ("kPartlyCloudyNight", 0xF6C3),  # cloud-moon
    ("kOvercast", 0xF0C2),      # cloud
    ("kRain", 0xF73D),          # cloud-rain
    ("kHeavyRain", 0xF740),     # cloud-showers-heavy
    ("kThunder", 0xF76C),       # cloud-bolt
    ("kSnow", 0xF2DC),          # snowflake
    ("kFog", 0xF75F),           # smog
]


def render(font_path, code, box):
    probe = ImageFont.truetype(font_path, 100)
    left, top, right, bottom = probe.getbbox(chr(code))
    size = int(100 * box / max(right - left, bottom - top))
    font = ImageFont.truetype(font_path, size)
    left, top, right, bottom = font.getbbox(chr(code))
    img = Image.new("L", (box, box), 255)
    x = (box - (right - left)) // 2 - left
    y = (box - (bottom - top)) // 2 - top
    ImageDraw.Draw(img).text((x, y), chr(code), font=font, fill=0)
    rows = []
    stride = box // 8
    for yy in range(box):
        for bx in range(stride):
            byte = 0
            for bit in range(8):
                if img.getpixel((bx * 8 + bit, yy)) < 128:
                    byte |= 0x80 >> bit
            rows.append(byte)
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font")
    args = ap.parse_args()
    font = args.font
    if not font:
        if not CACHE.exists():
            CACHE.parent.mkdir(parents=True, exist_ok=True)
            print("downloading", URL)
            urllib.request.urlretrieve(URL, CACHE)
        font = str(CACHE)
    lines = [
        "// Generated by tools/generate_weather_icons.py from Font Awesome Free (SIL OFL 1.1).",
        "// 1bpp, MSB first, 1 = black pixel. Index = enum class WeatherIcon.",
        "#ifndef APPS_WEATHER_WEATHER_ICONS_H_",
        "#define APPS_WEATHER_WEATHER_ICONS_H_",
        "",
        "#include <cstdint>",
        "",
    ]
    for box in SIZES:
        lines.append(f"inline constexpr uint8_t kWeatherIcons{box}[{len(ICONS)}][{box * box // 8}] = {{")
        for name, code in ICONS:
            data = render(font, code, box)
            lines.append(f"    // {name}")
            lines.append("    {" + ", ".join(f"0x{b:02x}" for b in data) + "},")
        lines.append("};")
        lines.append("")
    lines += ["#endif  // APPS_WEATHER_WEATHER_ICONS_H_", ""]
    OUT.write_text("\n".join(lines))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
